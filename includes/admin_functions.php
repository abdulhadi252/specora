/**
 * Validate password strength
 * @return string|null Error message or null if valid
 */
function validate_password(string $password): ?string
{
    if ($password === '') {
        return 'Password is required.';
    }
    if (strlen($password) < 8) {
        return 'Password must be at least 8 characters.';
    }
    if (!preg_match('/[A-Z]/', $password)) {
        return 'Password must contain at least one uppercase letter.';
    }
    if (!preg_match('/[a-z]/', $password)) {
        return 'Password must contain at least one lowercase letter.';
    }
    if (!preg_match('/[0-9]/', $password)) {
        return 'Password must contain at least one number.';
    }
    if (!preg_match('/[^a-zA-Z0-9]/', $password)) {
        return 'Password must contain at least one special character.';
    }
    return null;
}

/**
 * Validate confirm password matches
 * @return string|null Error message or null if valid
 */
function validate_confirm_password(string $password, string $confirm): ?string
{
    if ($confirm === '') {
        return 'Please confirm your password.';
    }
    if ($password !== $confirm) {
        return 'Passwords do not match.';
    }
    return null;
}

/**
 * Admin session timeout in seconds (default: 1800 = 30 minutes)
 */
define('ADMIN_SESSION_TIMEOUT', 1800);

/**
 * Start a secure session if not already started
 * Configures secure cookie parameters (httponly, samesite) to prevent XSS/CSRF session access.
 */
function ensure_session(): void
{
    if (session_status() === PHP_SESSION_NONE) {
        // Set secure session cookie parameters before starting
        session_set_cookie_params([
            'lifetime' => 0,
            'path'     => '/',
            'domain'   => '',
            'secure'   => isset($_SERVER['HTTPS']) && $_SERVER['HTTPS'] === 'on',
            'httponly' => true,
            'samesite' => 'Strict',
        ]);
        session_start();
    }
}

/**
 * Check if admin is logged in, redirect to login if not
 * Also enforces session timeout — auto-logout after inactivity.
 */
function require_admin_login(): void
{
    ensure_session();
    
    if (!isset($_SESSION['admin_logged_in']) || $_SESSION['admin_logged_in'] !== true) {
        http_response_code(302);
        header('Location: login.php');
        exit;
    }
    
    // ── Session timeout check ──
    if (isset($_SESSION['LAST_ACTIVITY']) && (time() - $_SESSION['LAST_ACTIVITY'] > ADMIN_SESSION_TIMEOUT)) {
        // Timeout exceeded — destroy session
        $_SESSION = [];
        if (ini_get("session.use_cookies")) {
            $params = session_get_cookie_params();
            setcookie(session_name(), '', time() - 42000,
                $params["path"], $params["domain"],
                $params["secure"], $params["httponly"]
            );
        }
        session_destroy();
        http_response_code(302);
        header('Location: login.php?timeout=1');
        exit;
    }
    
    // ── Update last activity timestamp ──
    $_SESSION['LAST_ACTIVITY'] = time();
}

/**
 * Render an error message for a specific field
 */
function field_error(string $fieldName, array $errors): string
{
    if (isset($errors[$fieldName])) {
        $msg = htmlspecialchars($errors[$fieldName]);
        return '<div class="field-err">' . $msg . '</div>';
    }
    return '';
}

/**
 * Render a preserved input value
 */
function old_value(string $fieldName): string
{
    return htmlspecialchars($_POST[$fieldName] ?? '');
}

/**
 * Generate or retrieve a CSRF token for the current session
 * @return string The CSRF token value
 */
function generate_csrf_token(): string
{
    ensure_session();
    if (empty($_SESSION['csrf_token'])) {
        $_SESSION['csrf_token'] = bin2hex(random_bytes(32));
    }
    return $_SESSION['csrf_token'];
}

/**
 * Validate a CSRF token against the session token
 * @param string|null $token The token from the form submission
 * @return bool True if token is valid
 */
function validate_csrf_token(?string $token): bool
{
    ensure_session();
    if (empty($_SESSION['csrf_token']) || empty($token)) {
        return false;
    }
    return hash_equals($_SESSION['csrf_token'], $token);
}

/**
 * Render a hidden CSRF token input field
 * @return string HTML for the hidden input
 */
function csrf_field(): string
{
    $token = generate_csrf_token();
    return '<input type="hidden" name="csrf_token" value="' . $token . '">';
}

